-- AI Project Idea Generator: Supabase PostgreSQL schema
-- Run this entire file in Supabase Dashboard -> SQL Editor -> New query.
create extension if not exists pgcrypto;

create table if not exists public.app_users (
  id uuid primary key default gen_random_uuid(),
  name varchar(80) not null check (char_length(trim(name)) between 2 and 80),
  email varchar(254) not null unique,
  password_hash text not null,
  role text not null default 'student' check (role in ('student', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.saved_ideas (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.app_users(id) on delete cascade,
  title varchar(180) not null check (char_length(trim(title)) between 3 and 180),
  domain varchar(60) not null check (domain in ('AI & Machine Learning','Web Development','IoT & Embedded','Cybersecurity','Environment','Healthcare & Wellness','Education','Open Innovation')),
  skill_level text not null default 'Beginner' check (skill_level in ('Beginner','Intermediate','Advanced')),
  idea_data jsonb not null check (jsonb_typeof(idea_data) = 'object'),
  created_at timestamptz not null default now(),
  unique (user_id, title)
);

create index if not exists idx_saved_ideas_user_created on public.saved_ideas(user_id, created_at desc);
create index if not exists idx_saved_ideas_domain on public.saved_ideas(domain);
create index if not exists idx_app_users_created on public.app_users(created_at desc);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists app_users_set_updated_at on public.app_users;
create trigger app_users_set_updated_at before update on public.app_users
for each row execute function public.set_updated_at();

-- The Express server uses the service-role key only on the server and checks
-- JWT identity/role before every private request. RLS is still enabled as a
-- defense-in-depth boundary for direct access using anon/authenticated roles.
alter table public.app_users enable row level security;
alter table public.saved_ideas enable row level security;

drop policy if exists "No direct public access to app users" on public.app_users;
create policy "No direct public access to app users" on public.app_users
  for all to anon, authenticated using (false) with check (false);
drop policy if exists "No direct public access to saved ideas" on public.saved_ideas;
create policy "No direct public access to saved ideas" on public.saved_ideas
  for all to anon, authenticated using (false) with check (false);

comment on table public.app_users is 'Application accounts; password hashes are generated by bcrypt in the Express backend.';
comment on table public.saved_ideas is 'Each user’s saved project idea shortlist; idea details are stored as validated JSONB.';
